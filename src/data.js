// Compute average rating and review count for a university.
export function getUniversityStats(universityId) {
  const uniReviews = reviews.filter((r) => r.universityId === universityId)
  if (uniReviews.length === 0) {
    return { avgRating: 0, count: 0, hasVerified: false }
  }
  const avgRating = uniReviews.reduce((sum, r) => sum + r.rating, 0) / uniReviews.length
  const hasVerified = uniReviews.some((r) => r.verified)
  return { avgRating, count: uniReviews.length, hasVerified }
}

export function getReviewsForUniversity(universityId) {
  return reviews.filter((r) => r.universityId === universityId)
}

export function getUniversityById(id) {
  return universities.find((u) => u.id === id)
}

